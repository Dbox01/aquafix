/**
 * Generate a one-shot Edge Function that carries the built site inside itself
 * and writes it into the public `app` Storage bucket.
 *
 *   npm run build && node scripts/make-publish-function.mjs <secret-path>
 *
 * Why this exists: the machine doing the building cannot always reach the
 * Supabase host directly (locked-down network egress), but the Supabase
 * management API can deploy a function, and a deployed function runs *inside*
 * Supabase where Storage is a local call. So the bundle travels as function
 * source rather than as an upload.
 *
 * Files are gzipped then base64'd — roughly a third the size of raw base64 of
 * the same content, which matters when the whole payload has to fit in a source
 * file.
 *
 * The function takes no input and always writes the same bytes, so the worst a
 * stranger who guesses the URL can do is republish the site as it already is.
 * It is still deleted immediately after use.
 */

import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const outDir = join(root, 'supabase', 'functions', 'publish');
const secret = process.argv[2];

if (!secret || secret.length < 16) {
  console.error('Pass an unguessable path segment: node scripts/make-publish-function.mjs <secret>');
  process.exit(1);
}

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.txt': 'text/plain; charset=utf-8',
};

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = walk(dist).map((file) => {
  const path = relative(dist, file).split('\\').join('/');
  return {
    path,
    type: TYPES[extname(file)] ?? 'application/octet-stream',
    // index.html and the service worker must not be cached, or a publish looks
    // like it did nothing. Hashed assets change name when they change.
    cache: path === 'index.html' || path === 'sw.js' ? '0' : '31536000',
    gz: gzipSync(readFileSync(file), { level: 9 }).toString('base64'),
  };
});

const source = `// GENERATED by scripts/make-publish-function.mjs — do not edit.
// Carries the built frontend and writes it to the public 'app' bucket.
// Delete this function once the publish has succeeded.

const FILES: { path: string; type: string; cache: string; gz: string }[] = ${JSON.stringify(files)};

const SECRET = ${JSON.stringify(secret)};

function inflate(b64: string): Uint8Array {
  const raw = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
  return raw;
}

Deno.serve(async (req) => {
  const url = new URL(req.url);
  if (!url.pathname.includes(SECRET)) {
    return new Response('Not found', { status: 404 });
  }

  const base = Deno.env.get('SUPABASE_URL');
  const key = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY');
  if (!base || !key) return new Response('Missing environment', { status: 500 });

  const results: string[] = [];

  for (const f of FILES) {
    // Decompress in the function so the payload travels small.
    const stream = new Response(inflate(f.gz)).body!.pipeThrough(new DecompressionStream('gzip'));
    const bytes = new Uint8Array(await new Response(stream).arrayBuffer());

    const res = await fetch(\`\${base}/storage/v1/object/app/\${f.path}\`, {
      method: 'POST',
      headers: {
        apikey: key,
        Authorization: \`Bearer \${key}\`,
        'Content-Type': f.type,
        'Cache-Control': f.cache,
        'x-upsert': 'true',
      },
      body: bytes,
    });
    results.push(\`\${res.ok ? 'ok  ' : 'FAIL'} \${f.path} (\${bytes.length} bytes)\${res.ok ? '' : ' ' + (await res.text())}\`);
  }

  return new Response(results.join('\\n') + '\\n', {
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  });
});
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'index.ts'), source);

const kb = Math.round(source.length / 1024);
console.log(`Wrote ${relative(root, join(outDir, 'index.ts'))} — ${files.length} files, ${kb} KB of source.`);
